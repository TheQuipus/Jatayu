function getEmailDomain(email: string): string | null {
  const atIndex = email.lastIndexOf("@");
  if (atIndex <= 0 || atIndex === email.length - 1) return null;
  return email.slice(atIndex + 1);
}

function getTld(domain: string): string | null {
  const tld = domain.split(".").pop();
  return tld ? tld.toLowerCase() : null;
}

export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}

export function isValidEmail(email: string): boolean {
  return getEmailValidationError(email) === null;
}

export function getEmailValidationError(
  email: string,
  options?: { requiredMessage?: string; invalidMessage?: string },
): string | null {
  const trimmed = email.trim();
  if (!trimmed) {
    return options?.requiredMessage ?? "Required";
  }
  if (trimmed.length > 254) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }
  if (!EMAIL_PATTERN.test(trimmed)) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }

  const atIndex = trimmed.lastIndexOf("@");
  const localPart = trimmed.slice(0, atIndex);
  const domain = getEmailDomain(trimmed);

  if (!localPart || !domain) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }
  if (localPart.startsWith(".") || localPart.endsWith(".") || localPart.includes("..")) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }
  if (domain.startsWith(".") || domain.endsWith(".") || domain.includes("..")) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }

  const tld = getTld(domain);
  if (!tld || !/^[a-z]{2,63}$/.test(tld)) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }
  if (COM_TLD_TYPOS.has(tld)) {
    return "Did you mean .com?";
  }
  if (!VALID_TLDS.has(tld)) {
    return options?.invalidMessage ?? "Enter a valid email address";
  }

  return null;
}
